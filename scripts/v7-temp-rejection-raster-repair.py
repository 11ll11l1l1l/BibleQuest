#!/usr/bin/env python3
"""Temporary, SHA-locked Lane Y Rejection derivative repair.
Only creates TYPE and THUMB from unchanged existing CLEAN; no art generation.
This file is removed from the proposed PR after generated bytes are verified.
"""
from __future__ import annotations
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, features

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "public/v7/images/emotion/bqv7-emotion-rejection-01.webp"
TYPE = ROOT / "public/v7/images/emotion/bqv7-emotion-rejection-01-with-text-en.webp"
THUMB = ROOT / "public/v7/images/emotion/bqv7-emotion-rejection-01-thumbnail.webp"
RECORD = ROOT / "data/v7/visual-assets/records/bqv7-emotion-rejection-01-derivatives.json"
SRC_SHA = "851925b93ad108f90aa1f0943259debcd9aef4db9181e488029a782882d2b448"
TAX_SHA = "e64366970838d62c11ea602dd606e0acfe5b0cb2"
LABEL = "Rejected / unwanted"
REF = "Psalm 27:10"
FONT = Path("/usr/share/fonts/truetype/noto/NotoSerif-Regular.ttf")

def sha256(contents: bytes) -> str:
    return hashlib.sha256(contents).hexdigest()

def details(path: Path) -> dict:
    b = path.read_bytes()
    with Image.open(path) as im:
        im.load()
        assert im.format == "WEBP", (path, im.format)
        w, h = im.size
    return {"imagePath": "/"+str(path.relative_to(ROOT / "public")).replace("\\", "/"),
            "format": "webp", "width": w, "height": h, "fileBytes": len(b),
            "sha256": sha256(b)}

def make():
    assert features.check("webp"), "Pillow WebP support is required"
    assert sha256(SRC.read_bytes()) == SRC_SHA, "CLEAN source changed; abort"
    assert FONT.is_file(), "SIL OFL Noto Serif not installed"
    with Image.open(SRC) as im:
        clean = im.convert("RGB")
    assert clean.size == (1024, 1024)
    # Real 4:5 thumbnail: crop preserves the approved subject's face/hand.
    # Reuses the documented source crop, not a collage or vector data-uri.
    clean.crop((120, 0, 939, 1024)).resize(
        (768, 960), Image.Resampling.LANCZOS
    ).save(THUMB, "WEBP", quality=92, method=6)

    canvas = Image.new("RGB", (1024, 1280), (21, 32, 44))
    canvas.paste(clean.crop((0, 0, 1024, 940)).resize((1024, 940)), (0, 340))
    draw = ImageDraw.Draw(canvas)
    size = 74
    font = ImageFont.truetype(str(FONT), size)
    while draw.textbbox((0, 0), LABEL, font=font)[2] > 810 and size > 52:
        size -= 1
        font = ImageFont.truetype(str(FONT), size)
    assert draw.textbbox((0, 0), LABEL, font=font)[2] <= 810
    draw.text((108, 130), LABEL, font=font, fill=(246, 241, 231))
    ref_font = ImageFont.truetype(str(FONT), 39)
    draw.text((110, 243), REF, font=ref_font, fill=(228, 190, 144))
    draw.line([(108, 323), (916, 323)], fill=(203, 171, 128), width=2)
    canvas.save(TYPE, "WEBP", quality=91, method=6)
    with Image.open(TYPE) as im:
        im.load()
        assert im.size == (1024,1280)
    with Image.open(THUMB) as im:
        im.load()
        assert im.size == (768,960)

    rec = json.loads(RECORD.read_text(encoding="utf-8"))
    assert rec["sourceMasterAssetId"] == "bqv7-emotion-rejection-01"
    cleanv = next(x for x in rec["variants"] if x["kind"] == "CLEAN")
    assert cleanv["sha256"] == SRC_SHA
    typev = {
        "kind": "TYPE", "locale": "en", **details(TYPE),
        "focalPoint": {"x": 0.52, "y": 0.52},
        "embeddedWording": {"label": LABEL, "scriptureReference": REF, "scriptureTextIncluded": False},
        "altText": "A young man sits apart from a nearby group, looking down. English title: Rejected / unwanted. Reference: Psalm 27:10.",
        "typography": {"method": "Pillow deterministically rasterized on unchanged CLEAN",
                       "fontFamily": "Noto Serif Regular", "fontLicense": "SIL OFL 1.1",
                       "locale": "en", "fontFilesDistributed": False,
                       "sourceCleanSha256": SRC_SHA},
        "qa": {"imageDecoded": True, "dimensionsMeasured": True, "sha256Measured": True,
               "sourceWordingExact": True, "scriptureReferenceOnly": True,
               "independentVisualQA": "pending", "builtAppBrowserQA": "pending",
               "productionReady": False}
    }
    thumbv = {
        "kind": "THUMB", "locale": None, **details(THUMB),
        "focalPoint": {"x": 0.56, "y": 0.42},
        "altText": "A young man sits on a low step apart from a group of friends, looking down.",
        "crop": {"sourceFileSha256": SRC_SHA, "sourceRectPixels": {
            "left": 120, "top": 0, "right": 939, "bottom": 1024},
            "targetAspectRatio": "4:5", "method": "Pillow LANCZOS actual 768x960 WebP crop"},
        "qa": {"imageDecoded": True, "dimensionsMeasured": True, "sha256Measured": True,
               "noBakedText": True, "independentVisualQA": "pending",
               "builtAppBrowserQA": "pending", "productionReady": False}
    }
    rec["variants"] = [cleanv,typev,thumbv]
    rec["status"] = "candidate_real_webp_scripture_reference_independent_browser_qa_pending"
    rec["bundleStatus"] = "real_clean_type_thumb_candidate_browser_qa_pending"
    rec["wordingEvidence"] = {
        "sourcePath": "src/features/library/emotion-taxonomy.js",
        "sourceBlobSha": TAX_SHA, "canonicalEmotionId": "rejected",
        "locale": "en", "exactLabel": LABEL, "reference": REF,
        "scriptureTextIncluded": False}
    rec.setdefault("generation", {})["derivatives"] = (
        "TYPE: separate licensed Noto Serif Pillow compositing from unchanged CLEAN; "
        "THUMB: actual 4:5 raster crop of unchanged CLEAN; no SVG/data URI.")
    rec["qc"] = {"sourceImageSha256Untouched": SRC_SHA,
                 "sourceImageWebPReused": True,
                 "typeAndThumbTrueWebP": True,
                 "referenceFromTaxonomy": REF,
                 "independentVisualQA": "pending",
                 "actualBuiltAppBrowserQA": "pending",
                 "servedByteSHA": "pending", "productionReady": False}
    rec.pop("inspectionEvidence", None)  # Stale SVG is retained in Git history.
    RECORD.write_text(json.dumps(rec, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    assert sha256(SRC.read_bytes()) == SRC_SHA
    print("REJECTION_RASTER_REPAIR_PASS")
    for f in (SRC,TYPE,THUMB):
        print(f.relative_to(ROOT), details(f))
    print("No candidate approved; independent QA and exact-head CI required.")

if __name__ == "__main__":
    make()
