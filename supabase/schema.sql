-- Security-definer membership helper avoids recursive RLS on the membership table.
-- It returns only a boolean and has an empty search_path to minimize privilege risk.
create or replace function private.is_bible_congregation_member(target_congregation uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.bible_congregation_members m
    where m.congregation_id = target_congregation
      and m.user_id = (select auth.uid())
      and m.active
  );
$$;

revoke all on function private.is_bible_congregation_member(uuid) from public;
grant usage on schema private to authenticated;
grant execute on function private.is_bible_congregation_member(uuid) to authenticated;

