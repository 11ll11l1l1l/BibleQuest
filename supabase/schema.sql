-- BibleQuest backend blueprint. This file is not deployed to the user's other Supabase projects.
-- Apply only to a dedicated BibleQuest project.

create table if not exists public.bible_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  xp integer not null default 0 check (xp >= 0),
  streak integer not null default 0 check (streak >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.bible_questions (
  id uuid primary key default gen_random_uuid(), external_id text unique,
  question_type text not null, book text, chapter integer, verse_start integer, verse_end integer,
  difficulty smallint not null default 1 check (difficulty between 1 and 5),
  prompt text not null, choices jsonb, answer jsonb, explanation text, reference_text text,
  content_class text not null default 'fact' check (content_class in ('fact','context','interpretation','wisdom','open_question')),
  source_name text not null, source_version text, source_url text, license text, attribution text,
  reviewed boolean not null default false, created_at timestamptz not null default now()
);

create table if not exists public.bible_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  question_id uuid references public.bible_questions(id) on delete set null,
  external_question_id text, correct boolean not null, response jsonb,
  xp_earned integer not null default 0, created_at timestamptz not null default now()
);

create table if not exists public.bible_mastery (
  user_id uuid not null references auth.users(id) on delete cascade,
  topic text not null, score numeric(5,2) not null default 0 check (score between 0 and 100),
  attempts integer not null default 0, correct integer not null default 0,
  next_review_at timestamptz, updated_at timestamptz not null default now(),
  primary key (user_id, topic)
);

create table if not exists public.bible_polls (
  id uuid primary key default gen_random_uuid(), prompt text not null, context text,
  options jsonb not null, scripture_refs jsonb, content_class text not null default 'open_question',
  active boolean not null default true, created_at timestamptz not null default now()
);

create table if not exists public.bible_poll_votes (
  poll_id uuid not null references public.bible_polls(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  option_index integer not null, created_at timestamptz not null default now(),
  primary key (poll_id, user_id)
);

create table if not exists public.bible_congregations (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete restrict,
  name text not null check (char_length(name) between 2 and 100),
  slug text unique,
  timezone text not null default 'Asia/Tokyo',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.bible_congregation_members (
  congregation_id uuid not null references public.bible_congregations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('member','facilitator','leader','admin')),
  display_name text,
  active boolean not null default true,
  joined_at timestamptz not null default now(),
  primary key (congregation_id, user_id)
);

-- Generic teams support couples, families, small groups, and game teams.
-- Private conversation answers are deliberately not stored here.
create table if not exists public.bible_teams (
  id uuid primary key default gen_random_uuid(),
  congregation_id uuid not null references public.bible_congregations(id) on delete cascade,
  created_by uuid not null references auth.users(id) on delete restrict,
  team_type text not null check (team_type in ('couple','family','small_group','game_team')),
  name text not null check (char_length(name) between 2 and 80),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.bible_team_members (
  team_id uuid not null references public.bible_teams(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (team_id, user_id)
);

create table if not exists public.bible_shared_sessions (
  id uuid primary key default gen_random_uuid(),
  congregation_id uuid not null references public.bible_congregations(id) on delete cascade,
  created_by uuid not null references auth.users(id) on delete restrict,
  session_type text not null check (session_type in ('team_sprint','detective','verse_hunt','conversation_circle','wisdom_table','pair_share','couples','poll','other')),
  title text,
  metadata jsonb not null default '{}'::jsonb,
  started_at timestamptz not null default now(),
  ended_at timestamptz
);

create table if not exists public.bible_session_participants (
  session_id uuid not null references public.bible_shared_sessions(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  team_id uuid references public.bible_teams(id) on delete set null,
  participation_points integer not null default 0 check (participation_points between 0 and 100),
  created_at timestamptz not null default now(),
  primary key (session_id, user_id)
);

-- Immutable dated events are the source for Today / This Week / All Time leaderboards.
-- Direct browser writes are intentionally forbidden. A trusted Edge Function/server should validate
-- game/session evidence and derive these events to prevent forged or spammed scores.
create table if not exists public.bible_score_events (
  id bigint generated by default as identity primary key,
  congregation_id uuid not null references public.bible_congregations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  team_id uuid references public.bible_teams(id) on delete set null,
  category text not null check (category in ('knowledge','reading','wisdom','mastery','consistency','group','couples')),
  points integer not null check (points between 1 and 100),
  source text not null,
  source_event_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (congregation_id, user_id, source_event_id)
);

create index if not exists bible_score_events_congregation_date_idx on public.bible_score_events (congregation_id, created_at desc);
create index if not exists bible_score_events_lane_idx on public.bible_score_events (congregation_id, category, created_at desc);
create index if not exists bible_score_events_user_idx on public.bible_score_events (user_id, created_at desc);

create table if not exists public.bible_badge_catalog (
  id text primary key,
  icon text not null,
  name text not null,
  category text not null,
  description text not null,
  threshold jsonb not null default '{}'::jsonb,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.bible_user_badges (
  congregation_id uuid not null references public.bible_congregations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  badge_id text not null references public.bible_badge_catalog(id) on delete restrict,
  metadata jsonb not null default '{}'::jsonb,
  earned_at timestamptz not null default now(),
  primary key (congregation_id, user_id, badge_id)
);

