create policy "devices own update" on public.bible_devices for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "devices own delete" on public.bible_devices for delete to authenticated using ((select auth.uid()) = user_id);

create policy "notes own read" on public.bible_notes for select to authenticated using ((select auth.uid()) = user_id);
create policy "notes own insert" on public.bible_notes for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "notes own update" on public.bible_notes for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "notes own delete" on public.bible_notes for delete to authenticated using ((select auth.uid()) = user_id);

create policy "progress own read" on public.bible_progress_snapshots for select to authenticated using ((select auth.uid()) = user_id);
create policy "progress own insert" on public.bible_progress_snapshots for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "progress own update" on public.bible_progress_snapshots for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

create policy "activity own read" on public.bible_activity_events for select to authenticated using ((select auth.uid()) = user_id);
create policy "activity own insert" on public.bible_activity_events for insert to authenticated with check ((select auth.uid()) = user_id);

