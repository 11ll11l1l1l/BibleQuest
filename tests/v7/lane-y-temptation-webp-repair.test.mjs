import test from 'node:test';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile, access} from 'node:fs/promises';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {LIBRARY_EMOTIONS} from '../../src/features/library/emotion-taxonomy.js';
const ROOT=fileURLToPath(new URL('../../',import.meta.url));
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const read=path=>readFile(join(ROOT,'public',path.slice(1)));
async function assertWebp(path,hash,dimensions) {
 const bytes=await read(path);
 assert.equal(bytes.toString('ascii',0,4),'RIFF');
 assert.equal(bytes.toString('ascii',8,12),'WEBP');
 assert.equal(sha(bytes),hash,'file content SHA256 must match recorded source');
 let dims;
 const chunk=bytes.toString('ascii',12,16);
 if(chunk==='VP8X')dims=[1+bytes.readUIntLE(24,3),1+bytes.readUIntLE(27,3)];
 else if(chunk==='VP8 ')dims=[bytes.readUInt16LE(26)&0x3fff,bytes.readUInt16LE(28)&0x3fff];
 else if(chunk==='VP8L')dims=[1+(bytes[21]|((bytes[22]&0x3f)<<8)),1+((bytes[22]>>6)|(bytes[23]<<2)|((bytes[24]&15)<<10))];
 else assert.fail('Unknown WebP encoding '+chunk);
 assert.deepEqual(dims,dimensions,'native encoded width and height');
 return bytes.length;
}

test('Lane Y temptation real WebP TYPE and source identity stay exact and unpublished', async()=>{
 const name='bqv7-emotion-temptation-01';
 const dir=join(ROOT,'data/v7/visual-assets/records');
 const master=JSON.parse(await readFile(join(dir,name+'.json'),'utf8'));
 const record=JSON.parse(await readFile(join(dir,name+'-derivatives.json'),'utf8'));
 const type=record.variants.find(x=>x.kind==='TYPE');
 const thumb=record.variants.find(x=>x.kind==='THUMB');
 assert.ok(type,'candidate English TYPE must exist');
 assert.equal(type.locale,'en');
 assert.equal(type.format,'webp');
 assert.equal(type.sha256,'0ace3ccd561e94133cab14fe1b29326b42c67ef6e72f65cd7c2364625b278aeb');
 assert.equal(type.imagePath,'/v7/images/emotion/'+name+'-with-text-en.webp');
 assert.equal(type.fileBytes,await assertWebp(type.imagePath,'0ace3ccd561e94133cab14fe1b29326b42c67ef6e72f65cd7c2364625b278aeb',[1024,1280]));
 assert.equal(master.sha256,'51bc3448770b8b69677db1e58c1a40f941506742777a583fbf85c3b462c5b675');
 assert.equal(master.imagePath,'/v7/images/emotion/'+name+'.webp');
 await assertWebp(master.imagePath,'51bc3448770b8b69677db1e58c1a40f941506742777a583fbf85c3b462c5b675',[1024,1024]);
 const existingThumb=thumb || master.variants?.find(x=>x.kind==='THUMB');
 assert.ok(existingThumb,'text-free THUMB retained');
 assert.equal(existingThumb.sha256,'96d2c67d3cef5d8b1e1285fa33d976516c5cc6ff9ab9cb0892c2ba93e514234f');
 await assertWebp(existingThumb.imagePath,'96d2c67d3cef5d8b1e1285fa33d976516c5cc6ff9ab9cb0892c2ba93e514234f',[existingThumb.width,existingThumb.height]);
 assert.ok(!record.productionCertified);
 assert.notEqual(record.qa?.productionReady,true);
 const proof=record.wordingEvidence;
 const source=LIBRARY_EMOTIONS.find(x=>x.id===proof?.canonicalEmotionId);
 assert.ok(source,'taxonomy ID must exist');
 assert.equal(proof.exactLabel,'Tempted');
 assert.equal(source.labels.en,proof.exactLabel);
 assert.ok(source.scripture.includes('1 Corinthians 10:13'));
 assert.equal(proof.reference,'1 Corinthians 10:13');
 assert.equal(proof.scriptureTextIncluded,false);
 assert.deepEqual(type.embeddedWording,{label:'Tempted',scriptureReference:'1 Corinthians 10:13',scriptureTextIncluded:false});
 assert.equal(record.qa.webpTypeExported,true,'stale missing-export flag must stay corrected');
 assert.equal(master.qc.typeWordingRequiresReplacement,true,'master still requires independent certification before promotion');
 assert.equal(master.qc.excludedNoncanonicalType.embeddedWording.label,'Temptation');
 assert.notEqual(type.sha256,master.qc.excludedNoncanonicalType.sha256);
 assert.ok(!master.variants.some(x=>x.kind==='TYPE'),'historical wrong label must stay unlisted');
});
